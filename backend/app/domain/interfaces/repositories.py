"""Repository interfaces (persistence ports).

Implementations live in infrastructure (e.g. SQLAlchemy) and are injected via DI.
Domain/application depend only on these abstractions.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any, Sequence

from app.domain.contracts.execution import Execution, ExecutionEvent, NodeExecution
from app.domain.contracts.pipeline import PipelineSpec, PipelineVersion


class Repository(ABC):
    """Marker/base for repositories."""


class ProjectRepository(Repository):
    @abstractmethod
    async def list(self, **filters: Any) -> Sequence[Any]: ...
    @abstractmethod
    async def get(self, project_id: str) -> Any | None: ...
    @abstractmethod
    async def create(self, data: dict[str, Any]) -> Any: ...
    @abstractmethod
    async def update(self, project_id: str, data: dict[str, Any]) -> Any | None: ...
    @abstractmethod
    async def delete(self, project_id: str) -> bool: ...


class PipelineRepository(Repository):
    @abstractmethod
    async def list(self, **filters: Any) -> Sequence[PipelineSpec]: ...
    @abstractmethod
    async def get(self, pipeline_id: str) -> PipelineSpec | None: ...
    @abstractmethod
    async def save(self, pipeline: PipelineSpec) -> PipelineSpec: ...
    @abstractmethod
    async def delete(self, pipeline_id: str) -> bool: ...
    @abstractmethod
    async def create_version(self, version: PipelineVersion) -> PipelineVersion: ...
    @abstractmethod
    async def get_version(self, pipeline_id: str, version: str | None = None) -> PipelineVersion | None: ...
    @abstractmethod
    async def list_versions(self, pipeline_id: str) -> Sequence[PipelineVersion]: ...


class ExecutionRepository(Repository):
    @abstractmethod
    async def list(self, **filters: Any) -> Sequence[Execution]: ...
    @abstractmethod
    async def get(self, execution_id: str) -> Execution | None: ...
    @abstractmethod
    async def create(self, execution: Execution) -> Execution: ...
    @abstractmethod
    async def update(self, execution: Execution) -> Execution: ...
    @abstractmethod
    async def save_node_execution(self, node_execution: NodeExecution) -> NodeExecution: ...
    @abstractmethod
    async def list_node_executions(self, execution_id: str) -> Sequence[NodeExecution]: ...
    @abstractmethod
    async def append_event(self, event: ExecutionEvent) -> ExecutionEvent: ...
    @abstractmethod
    async def list_events(self, execution_id: str, after: str | None = None) -> Sequence[ExecutionEvent]: ...


class ArtifactRepository(Repository):
    @abstractmethod
    async def create(self, metadata: dict[str, Any]) -> Any: ...
    @abstractmethod
    async def get(self, artifact_id: str) -> Any | None: ...
    @abstractmethod
    async def list_for_execution(self, execution_id: str) -> Sequence[Any]: ...


class DatasetRepository(Repository):
    @abstractmethod
    async def list_datasets(self, **filters: Any) -> Sequence[Any]: ...
    @abstractmethod
    async def get_dataset(self, dataset_id: str) -> Any | None: ...
    @abstractmethod
    async def save_dataset(self, dataset: Any) -> Any: ...
    @abstractmethod
    async def list_sources(self, **filters: Any) -> Sequence[Any]: ...
    @abstractmethod
    async def list_ingestion_jobs(self, **filters: Any) -> Sequence[Any]: ...


class ModelRepository(Repository):
    @abstractmethod
    async def list_models(self, **filters: Any) -> Sequence[Any]: ...
    @abstractmethod
    async def get_model(self, model_id: str) -> Any | None: ...
    @abstractmethod
    async def save_model(self, model: Any) -> Any: ...


class ProviderRepository(Repository):
    @abstractmethod
    async def list_providers(self, **filters: Any) -> Sequence[Any]: ...
    @abstractmethod
    async def get_provider(self, provider_id: str) -> Any | None: ...
    @abstractmethod
    async def save_provider_config(self, config: Any) -> Any: ...


class ExperimentRepository(Repository):
    @abstractmethod
    async def list(self, **filters: Any) -> Sequence[Any]: ...
    @abstractmethod
    async def get(self, experiment_id: str) -> Any | None: ...
    @abstractmethod
    async def save(self, experiment: Any) -> Any: ...


class EvaluationRepository(Repository):
    @abstractmethod
    async def list_runs(self, **filters: Any) -> Sequence[Any]: ...
    @abstractmethod
    async def save_run(self, run: Any) -> Any: ...
    @abstractmethod
    async def get_results(self, **filters: Any) -> Any | None: ...


class CustomNodeRepository(Repository):
    @abstractmethod
    async def list(self, **filters: Any) -> Sequence[Any]: ...
    @abstractmethod
    async def get(self, node_id: str) -> Any | None: ...
    @abstractmethod
    async def save(self, node: Any) -> Any: ...
    @abstractmethod
    async def list_versions(self, node_id: str) -> Sequence[Any]: ...
    @abstractmethod
    async def save_version(self, node_id: str, version: Any) -> Any: ...
