"""Generate Python scripts from a pipeline graph.

Reference pipelines are exported as fully standalone scripts: the pure
algorithms module is embedded verbatim and only the standard library is used.

Pipelines that declare a real provider (Hugging Face, Ollama, OpenAI) are
exported with explicit ``PROVIDER_CONFIG`` and ``provider_hooks``. Those scripts
import the RAG Studio provider layer instead of embedding SDK code, and fail
loudly when no real provider is configured. No API key is ever written into the
exported file.
"""

from __future__ import annotations

import inspect
import textwrap
from pathlib import Path
from typing import Any

from app.components import algorithms as alg
from app.components.corpus import dataset_id_from_pipeline, load_documents_for_dataset

_REFERENCE_VALUES = {"", "reference", "hash", "mock"}
_CAPABILITIES = {
    "embedding_provider": "embeddings",
    "rerank_provider": "reranking",
    "generation_provider": "generation",
}

_STANDALONE_TEMPLATE = '''#!/usr/bin/env python3
# Generated by RAG Studio. Standalone: requires only the Python standard library.
# Algorithms below are the deterministic reference implementation (hash vectors,
# lexical reranking, extractive generation), not trained models.
__ALGORITHMS_SOURCE__


PIPELINE_CONFIG = __PIPELINE_CONFIG__
EXPORT_QUERY = __EXPORT_QUERY__
DOCUMENTS = __DOCUMENTS__


def main() -> None:
    import argparse
    import json

    parser = argparse.ArgumentParser(description="Run a RAG Studio pipeline export.")
    parser.add_argument("query", nargs="?", default=EXPORT_QUERY, help="Query to answer")
    parser.add_argument("--json", action="store_true", help="Print the full result as JSON")
    args = parser.parse_args()

    result = run_pipeline(args.query, PIPELINE_CONFIG, DOCUMENTS)
    if args.json:
        print(json.dumps(result, indent=2))
        return

    print(f"Query: {result['query']}")
    print()
    print("Answer:")
    print(result["answer"]["text"])
    print()
    print("Sources:")
    for item in result["selected"]:
        label = item.get("title") or item.get("chunk_id") or item["id"]
        print(f"  [{item['rank']}] {label} (score {item['score']:.3f})")
    print()
    metrics = result["metrics"]
    print(
        "chunks={chunks} retrieved={retrieved} selected={selected} tokens={tokens}".format(
            **metrics
        )
    )


if __name__ == "__main__":
    main()
'''

_PROVIDER_TEMPLATE = '''#!/usr/bin/env python3
# Generated by RAG Studio. Requires the RAG Studio backend, not just stdlib.
# Configure credentials with environment variables (OPENAI_API_KEY,
# OLLAMA_BASE_URL, HF_*) or PATCH /api/v1/providers/settings first.
# No API key is embedded in this file. Provider resolution is strict: if no
# real model is available the script fails instead of using hash vectors.
__ALGORITHMS_SOURCE__

import asyncio
import os
import sys

BACKEND_PATH = __BACKEND_PATH__
if os.path.isdir(BACKEND_PATH) and BACKEND_PATH not in sys.path:
    sys.path.insert(0, BACKEND_PATH)


PIPELINE_CONFIG = __PIPELINE_CONFIG__
PROVIDER_CONFIG = __PROVIDER_CONFIG__
EXPORT_QUERY = __EXPORT_QUERY__
DOCUMENTS = __DOCUMENTS__

_RESOLUTIONS = {}


def _resolution(capability: str):
    """Resolve and cache one real provider per capability."""
    if capability not in _RESOLUTIONS:
        from app.providers import resolver

        config = PROVIDER_CONFIG[capability]
        resolve = {
            "embeddings": resolver.resolve_embeddings,
            "reranking": resolver.resolve_reranker,
            "generation": resolver.resolve_generator,
        }[capability]
        _RESOLUTIONS[capability] = resolve(
            config["provider"], config["model"] or None
        )
    return _RESOLUTIONS[capability]


def _embed_texts(texts, config=None):
    resolution = _resolution("embeddings")
    items = asyncio.run(resolution.implementation.embed_texts([str(t) for t in texts]))
    return [
        {"vector": list(item.vector or []), "item_id": item.item_id, "model": item.model}
        for item in items
    ]


def _rerank(query, candidates, config=None):
    from app.domain.contracts.data import Query, RetrievedCandidate

    resolution = _resolution("reranking")
    question = query if isinstance(query, Query) else Query(id="query_current", text=str(query))
    records = []
    for index, value in enumerate(candidates):
        item = value if isinstance(value, dict) else value.model_dump()
        records.append(
            RetrievedCandidate(
                id=str(item.get("id") or f"cand_{index}"),
                content=item.get("content"),
                chunk_id=item.get("chunk_id"),
                document_id=item.get("document_id"),
                score=float(item.get("score") or 0.0),
                rank=item.get("rank"),
                metadata=dict(item.get("metadata") or {}),
                scores=dict(item.get("scores") or {}),
            )
        )
    ranked = asyncio.run(resolution.implementation.rerank(question, records, config={}))
    return [
        {
            "id": item.id,
            "content": item.content,
            "chunk_id": item.chunk_id,
            "document_id": item.document_id,
            "score": item.score,
            "rank": item.rank,
            "metadata": item.metadata,
            "scores": item.scores,
            "source": item.source,
        }
        for item in ranked
    ]


def _generate(prompt, config=None):
    from app.domain.contracts.data import Prompt

    resolution = _resolution("generation")
    request = prompt if isinstance(prompt, Prompt) else Prompt(id="prompt_current", text=str(prompt))
    answer = asyncio.run(resolution.implementation.generate(request, config=dict(config or {})))
    return {
        "text": answer.text,
        "citations": answer.citations,
        "usage": answer.usage,
    }


PROVIDER_HOOKS = {
    "embed_texts": _embed_texts,
    "rerank": _rerank,
    "generate": _generate,
}


def main() -> None:
    import argparse
    import json

    parser = argparse.ArgumentParser(description="Run a real-provider RAG Studio export.")
    parser.add_argument("query", nargs="?", default=EXPORT_QUERY, help="Query to answer")
    parser.add_argument("--json", action="store_true", help="Print the full result as JSON")
    args = parser.parse_args()

    result = run_pipeline(args.query, PIPELINE_CONFIG, DOCUMENTS, provider_hooks=PROVIDER_HOOKS)
    if args.json:
        print(json.dumps(result, indent=2, default=str))
        return

    print(f"Query: {result['query']}")
    print()
    print("Answer:")
    print(result["answer"]["text"])
    print()
    print("Sources:")
    for item in result["selected"]:
        label = item.get("title") or item.get("chunk_id") or item["id"]
        print(f"  [{item['rank']}] {label} (score {item['score']:.3f})")
    print()
    metrics = result["metrics"]
    print(
        "chunks={chunks} retrieved={retrieved} selected={selected} tokens={tokens}".format(
            **metrics
        )
    )


if __name__ == "__main__":
    main()
'''


def _render(template: str, **values: Any) -> str:
    """Replace sentinel tokens without f-string brace escaping."""
    result = template
    for name, value in values.items():
        result = result.replace(f"__{name}__", str(value))
    return result


def generate_python_script(
    pipeline: Any,
    *,
    query: str | None = None,
    documents: list[dict[str, str]] | None = None,
) -> str:
    algorithms_source = textwrap.dedent(inspect.getsource(alg)).rstrip()
    config = alg.config_from_pipeline(pipeline)
    export_query = str(query or alg.DEFAULT_QUERY)
    source_documents = (
        documents
        if documents is not None
        else load_documents_for_dataset(dataset_id_from_pipeline(pipeline))
    )
    model_settings = {
        "embeddings": "embedding_model",
        "reranking": "rerank_model",
        "generation": "generation_model",
    }
    provider_config = {
        capability: {
            "provider": str(config.get(setting) or "auto"),
            "model": str(config.get(model_settings[capability]) or ""),
        }
        for setting, capability in _CAPABILITIES.items()
    }
    uses_real_providers = any(
        str(provider_config[capability]["provider"]).strip().lower() not in _REFERENCE_VALUES
        for capability in provider_config
    )
    if not uses_real_providers:
        return _render(
            _STANDALONE_TEMPLATE,
            ALGORITHMS_SOURCE=algorithms_source,
            PIPELINE_CONFIG=repr(config),
            EXPORT_QUERY=repr(export_query),
            DOCUMENTS=repr(source_documents),
        )

    backend_path = str(Path(__file__).resolve().parents[2])
    return _render(
        _PROVIDER_TEMPLATE,
        BACKEND_PATH=repr(backend_path),
        ALGORITHMS_SOURCE=algorithms_source,
        PIPELINE_CONFIG=repr(config),
        PROVIDER_CONFIG=repr(provider_config),
        EXPORT_QUERY=repr(export_query),
        DOCUMENTS=repr(source_documents),
    )
